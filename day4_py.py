def failure_router(state):
    # <<< THE DECISION TO SWITCH: if a model failed, route to the fallback node
    if state['ok_a'] and state['ok_b']:
        return 'judge'
    return 'fallback'

def winner_router(state):
    if state['winner'] == 'a':
        return 'pick_a'
    return 'pick_b'

from langgraph.graph import StateGraph, START, END

g = StateGraph(State)

g.add_node('model_a', model_a)
g.add_node('model_b', model_b)
g.add_node('check', check)
g.add_node('fallback', fallback)
g.add_node('judge', judge)
g.add_node('pick_a', pick_a)
g.add_node('pick_b', pick_b)

g.add_edge(START, 'model_a')
g.add_edge(START, 'model_b')
g.add_edge(['model_a', 'model_b'], 'check')                          # check waits for BOTH
g.add_conditional_edges('check', failure_router, ['fallback', 'judge'])
g.add_edge('fallback', 'judge')
g.add_conditional_edges('judge', winner_router, ['pick_a', 'pick_b'])
g.add_edge('pick_a', END)
g.add_edge('pick_b', END)

app = g.compile()

