SIMULATE_FAIL = ""

def ask(llm, prompt):
    # always returns plain text (some models return a list of blocks)
    content = llm.invoke(prompt).content
    if isinstance(content, list):
        return ''.join(b if isinstance(b, str) else b.get('text', '') for b in content)
